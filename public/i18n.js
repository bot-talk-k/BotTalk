/** Detect language */
function detectLanguage() {
  const stored = localStorage.getItem('lang');
  if (stored && (stored === 'zh' || stored === 'en')) return stored;
  const nav = (navigator.language || navigator.userLanguage || 'zh').toLowerCase();
  return nav.startsWith('zh') ? 'zh' : 'en';
}

/** Current language */
let currentLang = detectLanguage();

/** Get a translated string */
function t(key) {
  return (I18N[currentLang] && I18N[currentLang][key]) || (I18N.zh[key]) || key;
}

/** Apply language to all elements with data-i18n attribute */
function applyLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('lang', lang);

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = val;
    } else {
      el.textContent = val;
    }
  });

  // Update lang toggle button text
  const toggle = document.getElementById('lang-toggle');
  if (toggle) {
    toggle.textContent = lang === 'zh' ? 'EN' : '中';
  }

  // Refresh API docs test messages with new language
  if (typeof updateApiDocs === 'function') {
    updateApiDocs();
  }
}
